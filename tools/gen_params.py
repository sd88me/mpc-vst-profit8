#!/usr/bin/env python3
"""vst/params.json -> src/params_gen.h: the parameter table of the native front end (src/Profit08Plugin.cpp).

The VST order is the released 0.1.x wrapper build's: the 245 keys of vst/params.json (= vst/params.lock, checked), then the 37 hidden
"<key>__open" flags its layout's popups added (indices 245..281). This build keeps those indices: 245 is ui_open (which drawn
pick-list is open), 246..281 are inert reserved slots, and new parameters are appended from 282 on. Append only.
"""
import json, os

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
P = json.load(open(os.path.join(ROOT, "vst", "params.json")))["params"]
LOCK = [l.strip() for l in open(os.path.join(ROOT, "vst", "params.lock")) if l.strip()]
RELEASED_POPUPS = 37            # vst/layout.conf's popups in 0.1.3 (gen_vst.py: one "<key>__open" each, after the list)
UI_STEPS = 48                   # ui_open 0..47: 0 = closed, k + 1 = pick-list k
FAV_SLOTS = 64

keys = [p["key"] for p in P]
if keys[:len(LOCK)] != LOCK or len(keys) != len(LOCK):
    raise SystemExit("vst/params.json no longer matches vst/params.lock: the order is frozen (append only)")
idx = {k: i for i, k in enumerate(keys)}

FL = dict(kMomentary=1, kText=2, kDyn=4, kChoice=8, kUi=16, kReserved=32, kStep=128, kTile=256, kNoAuto=512, kPolled=1024, kLocal=4096)
out = ["/* generated by tools/gen_params.py from vst/params.json: do not edit. One row per parameter, in the frozen VST order. */",
       "#pragma once",
       "#if defined(__aarch64__)\n#define P8_QUALITY_DEF 1.0f   /* High 2x on 64-bit MPCs */\n#else\n#define P8_QUALITY_DEF 0.0f   /* Eco 1x on the Force */\n#endif",
       "enum { %s };" % ", ".join("%s = %d" % kv for kv in FL.items()),
       "struct PSpec { const char *key, *name; float min, max, def; int flags; const char *const *choices; int nchoices; int stepTarget; float stepDelta; };",
       ""]
rows = []


def F(v):
    t = "%g" % v
    return t + ("f" if ("." in t or "e" in t) else ".0f")


def row(key, name, lo, hi, d, fl, ch="nullptr", n=0, st=-1, sd=0.0):
    rows.append("    {%s, %s, %s, %s, %s, %d, %s, %d, %d, %s}," % (json.dumps(key), json.dumps(name), F(lo), F(hi), F(d), fl, ch, n, st, F(sd)))


for i, p in enumerate(P):
    k = p["key"]
    fl, ch, n, st, sd = 0, "nullptr", 0, -1, 0.0
    if "options" in p:
        fl |= FL["kChoice"] | FL["kPolled"]
        opts = p["options"]
        out.append("static const char *const ch_%d[] = {%s};" % (i, ", ".join(json.dumps(o) for o in opts)))
        ch, n = "ch_%d" % i, len(opts)
        lo, hi, d = 0, len(opts) - 1, p["default"]
    else:
        lo, hi, d = p["min"], p["max"], p["default"]
        if k.startswith("bank_slot_") or k.startswith("patch_slot_"):
            fl |= FL["kMomentary"] | FL["kText"] | FL["kTile"] | FL["kNoAuto"]      # list tiles: tap = pick, lit = "<key>_on"
        elif p.get("momentary"):
            fl |= FL["kMomentary"] | FL["kNoAuto"]
            if p.get("step_of"):
                fl |= FL["kStep"]
                st, sd = idx[p["step_of"]], p.get("step_delta", 1)
        elif p.get("display") == "string":
            fl |= FL["kText"] | FL["kNoAuto"]                                        # readouts: the value is a change counter
            lo, hi = 0, 1023
        else:
            fl |= FL["kPolled"]
            if p.get("dynamic_display"):
                fl |= FL["kDyn"]
    if k in ("browse_bank_index", "patch_page_index"):
        fl |= FL["kNoAuto"]
    if k == "quality":
        rows.append("    {%s, %s, 0.0f, 1.0f, P8_QUALITY_DEF, %d, %s, %d, -1, 0.0f}," % (json.dumps(k), json.dumps(p["name"]), fl, ch, n))
        continue
    row(k, p["name"], lo, hi, d, fl, ch, n, st, sd)

row("ui_open", "Pick List", 0, UI_STEPS - 1, 0, FL["kUi"] | FL["kNoAuto"])
for j in range(1, RELEASED_POPUPS):
    row("rsv_%d" % (len(P) + j), "Reserved %d" % j, 0, 1, 0, FL["kReserved"] | FL["kNoAuto"])
base = len(P) + RELEASED_POPUPS
row("fav_add", "+ Favourite", 0, 1, 0, FL["kLocal"] | FL["kMomentary"] | FL["kNoAuto"])
row("fav_del", "- Favourite", 0, 1, 0, FL["kLocal"] | FL["kMomentary"] | FL["kNoAuto"])

out += ["", "static const PSpec g_pspecs[] = {"] + rows + ["};",
        "static const int kNumParams = %d;" % (base + 2),
        "static const int kNumEngineParams = %d;   // 0 .. this - 1 are the engine's keys" % len(P),
        "static const int kUiParam = %d;" % len(P),
        "static const int kFavAdd = %d, kFavDel = %d, kFavSlots = %d;" % (base, base + 1, FAV_SLOTS), ""]
open(os.path.join(ROOT, "src", "params_gen.h"), "w").write("\n".join(out))
print("src/params_gen.h: %d params (%d engine, ui_open, %d reserved, 2 favourite keys)" % (base + 2, len(P), RELEASED_POPUPS - 1))
